#!/usr/bin/env node
/*
 * frontx-ui-grid-css: writes the Grid step rules for a config.
 *
 *   frontx-ui-grid-css <config.json | config.mjs> <output.css>
 *
 * `@container` conditions cannot read `var()`, so every container step
 * width has to be a literal in CSS; this script turns a GridConfig into
 * those rules. The kit's grid-steps.css is this script's output for the
 * default config (a test keeps them equal). Rules are scoped by the config
 * name through `data-fx-grid`, never by a CSS Module class, so a custom
 * config's CSS coexists with the default.
 *
 * Shipped as a plain dependency-free ESM file, so it repeats the config
 * checks of validateGridConfig (grid-config.ts) instead of importing them;
 * a test runs both over the same invalid configs.
 */
import { realpathSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { extname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SIZE_CLASSES = ['small', 'medium', 'large'];
const NAME_PATTERN = /^[a-z][a-z0-9-]*$/;
const TOKEN_PATTERN = /^--[a-z][a-z0-9-]*$/;
const LENGTH_PATTERN = /^(?:\d+(?:\.\d+)?|\.\d+)(?:px|rem|em)$/;

function validRange(range, columns) {
  return (
    !!range &&
    Number.isInteger(range.min) &&
    Number.isInteger(range.preferred) &&
    Number.isInteger(range.max) &&
    range.min >= 1 &&
    range.min <= range.preferred &&
    range.preferred <= range.max &&
    range.max <= columns
  );
}

export function validateConfig(config) {
  if (!config || typeof config !== 'object') throw new Error('Grid config must be an object');
  if (typeof config.name !== 'string' || !NAME_PATTERN.test(config.name)) {
    throw new Error('Grid config name must be a lowercase CSS-safe name');
  }
  if (!Number.isInteger(config.columns) || config.columns < 1) throw new Error('Grid columns must be an integer >= 1');
  if (typeof config.rowHeight !== 'string' || !LENGTH_PATTERN.test(config.rowHeight) || parseFloat(config.rowHeight) <= 0) {
    throw new Error('Grid rowHeight must be a positive CSS length in px, rem or em');
  }
  if (!Array.isArray(config.steps) || config.steps.length === 0) throw new Error('Grid steps must be nonempty');
  const names = new Set();
  let previousWidth = -1;
  for (const step of config.steps) {
    if (!step || typeof step.name !== 'string' || !NAME_PATTERN.test(step.name) || names.has(step.name)) {
      throw new Error('Grid step names must be unique lowercase CSS-safe names');
    }
    if (!Number.isFinite(step.minWidth) || step.minWidth < 0 || step.minWidth <= previousWidth) {
      throw new Error('Grid step widths must be finite, nonnegative, and strictly increasing');
    }
    if (typeof step.gap !== 'string' || !TOKEN_PATTERN.test(step.gap)) {
      throw new Error(`Grid step ${step.name} gap must be a CSS token reference`);
    }
    names.add(step.name);
    previousWidth = step.minWidth;
  }
  if (config.steps[0].minWidth !== 0) throw new Error('Grid first step must start at 0');
  for (const size of SIZE_CLASSES) {
    const steps = config.sizes?.[size];
    if (!steps || typeof steps !== 'object') throw new Error(`Grid size ${size} is missing`);
    for (const name of names) {
      if (!validRange(steps[name], config.columns)) {
        throw new Error(`Grid size ${size} step ${name} needs 1 <= min <= preferred <= max <= columns`);
      }
    }
  }
  if (config.heights?.low !== 1 || config.heights?.high !== 2) {
    throw new Error('Grid heights must be low 1 and high 2');
  }
}

export function generateGridCss(config) {
  validateConfig(config);
  const grid = `:where([data-fx-grid="${config.name}"])`;
  const item = `${grid} > :where([data-fx-grid-item])`;
  const rules = config.steps.map(step => {
    // Columns and the fixed row track are set once, in the base rule; only the gap changes per step.
    const columns =
      step.minWidth === 0
        ? ` grid-template-columns: repeat(var(--fx-grid-columns, ${config.columns}), minmax(0, 1fr)); grid-auto-rows: var(--fx-grid-row-height, ${config.rowHeight});`
        : '';
    const lines = [
      `${item} { grid-column: var(--fx-grid-col-${step.name}); grid-row: var(--fx-grid-row-${step.name}); }`,
      `${grid} {${columns} gap: var(--fx-grid-gap, var(${step.gap})); }`,
    ];
    if (step.minWidth === 0) return lines.join('\n');
    return `@container fx-grid (min-width: ${step.minWidth}px) {\n${lines.map(line => `  ${line}`).join('\n')}\n}`;
  });
  return `/* Generated by frontx-ui-grid-css. */\n${rules.join('\n\n')}\n`;
}

async function main() {
  const [input, output] = process.argv.slice(2);
  if (!input || !output) throw new Error('Usage: frontx-ui-grid-css <config.json|config.mjs> <output.css>');
  const path = resolve(input);
  const extension = extname(path);
  if (extension !== '.json' && extension !== '.mjs' && extension !== '.js') {
    throw new Error('Grid config must be a .json file or an ES module (.mjs, .js) with a default export');
  }
  let config;
  if (extension === '.json') {
    config = JSON.parse(await readFile(path, 'utf8'));
  } else {
    const module = await import(pathToFileURL(path).href);
    if (!('default' in module)) throw new Error(`Grid config module ${input} has no default export`);
    config = module.default;
  }
  await writeFile(resolve(output), generateGridCss(config));
}

// Run as a command, also through the symlink npm puts in node_modules/.bin; stay inert when imported.
function invokedDirectly() {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (invokedDirectly()) {
  main().catch(error => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
