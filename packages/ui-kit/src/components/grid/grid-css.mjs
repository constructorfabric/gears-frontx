/*
 * The Grid step-rule generator: turns a GridConfig into the stylesheet the
 * component imports. The frontx-ui-grid-css command is a thin executable over
 * this module, and the tests read generateGridCss from it in process, so the
 * module carries no CLI of its own - a file a test imports cannot carry the
 * executable's shebang.
 *
 * The config checks are grid-config-check.mjs, imported by this relative path
 * both from this directory in the repository and from dist/, where the build
 * copies it beside the command and this module.
 */
import { validateGridConfig } from './grid-config-check.mjs';

export function generateGridCss(config, { allowDefaultName = false } = {}) {
  validateGridConfig(config, { allowDefaultName });
  const grid = `:where([data-fx-grid="${config.name}"])`;
  const item = `${grid} > :where([data-fx-grid-item])`;
  const rules = config.steps.map(step => {
    // Columns and the fixed row track are set once, in the base rule; only the gap changes per step.
    const columns =
      step.minWidth === 0
        ? ` grid-template-columns: repeat(var(--_grid-columns, ${config.columns}), minmax(0, 1fr)); grid-auto-rows: var(--grid-row-height, ${config.rowHeight});`
        : '';
    const lines = [
      `${item} { grid-column: var(--_grid-col-${step.name}, auto); grid-row: var(--_grid-row-${step.name}, auto); }`,
      `${grid} {${columns} gap: var(--grid-gap, var(${step.gap})); }`,
    ];
    if (step.minWidth === 0) return lines.join('\n');
    return `@container fx-grid (min-width: ${step.minWidth}px) {\n${lines.map(line => `  ${line}`).join('\n')}\n}`;
  });
  return `/* Generated by frontx-ui-grid-css, format 1. Regenerate with frontx-ui-grid-css after a breaking ui-kit release. */\n${rules.join('\n\n')}\n`;
}
